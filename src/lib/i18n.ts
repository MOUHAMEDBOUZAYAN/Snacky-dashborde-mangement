export type Locale = "fr" | "en" | "ar";

export const LOCALES: readonly Locale[] = ["fr", "en", "ar"] as const;

export const DEFAULT_LOCALE: Locale = "fr";

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "fr" || value === "en" || value === "ar";
}

/** Cycle FR → EN → AR → FR. */
export function nextLocale(current: Locale): Locale {
  const index = LOCALES.indexOf(current);
  return LOCALES[(index + 1) % LOCALES.length] ?? DEFAULT_LOCALE;
}

/** Short label shown on the language toggle button. */
export function localeToggleLabel(current: Locale): string {
  const next = nextLocale(current);
  if (next === "fr") return "FR";
  if (next === "en") return "EN";
  return "ع";
}

export function localeHtmlLang(locale: Locale): string {
  if (locale === "ar") return "ar";
  if (locale === "en") return "en";
  return "fr";
}

export function localeDir(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

export function localeDateTag(locale: Locale): string {
  if (locale === "ar") return "ar-MA";
  if (locale === "en") return "en-GB";
  return "fr-FR";
}

